CREATE DATABASE JUSTLIFECASESTUDY;

CREATE TABLE `USERS` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `USERNAME` VARCHAR(50) NOT NULL,
  `PASSWORD` VARCHAR(128) NOT NULL,
  `FULL_NAME` VARCHAR(100) NOT NULL,
  `ROLE` VARCHAR(50) NOT NULL,
  `IS_ACTIVE` bit(1) DEFAULT b'0',
  `CREATED_DT` timestamp NULL DEFAULT NULL,
  `UPDATED_DT` timestamp NULL DEFAULT current_timestamp(),
   PRIMARY KEY (`ID`),
   KEY `USERNAME` (`USERNAME`)
);

CREATE TABLE `VEHICLES` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `CAR_NAME` VARCHAR(100) NOT NULL,
  `CAR_REG_NUMBER` VARCHAR(10) NOT NULL,
  `IS_ACTIVE` bit(1) DEFAULT b'0',
  `CREATED_DT` timestamp NULL DEFAULT NULL,
  `UPDATED_DT` timestamp NULL DEFAULT current_timestamp(),
   PRIMARY KEY (`ID`),
   KEY `CAR_NAME` (`CAR_NAME`),
   KEY `CAR_REG_NUMBER` (`CAR_REG_NUMBER`)
);


CREATE TABLE `PROFESSIONAL` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `PROFESSIONAL_ID` VARCHAR(10) NOT NULL,
  `NAME` VARCHAR(100) NOT NULL,
  `MOBILE_NUMBER` VARCHAR(10) NOT NULL,
  `SERVICE_TYPE` VARCHAR(20) NOT NULL,
  `IS_ACTIVE` bit(1) DEFAULT b'0',
  `CREATED_DT` timestamp NULL DEFAULT NULL,
  `UPDATED_DT` timestamp NULL DEFAULT current_timestamp(),
   PRIMARY KEY (`ID`),
   KEY `PROFESSIONAL_ID` (`PROFESSIONAL_ID`)
);


