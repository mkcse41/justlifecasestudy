CREATE TABLE `BOOKINGS` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `BOOKING_ID` VARCHAR(20) NOT NULL,
  `CUSTOMER_ID` BIGINT NOT NULL,
  `STARTED_AT` timestamp NULL DEFAULT NULL,
  `DURATION_HOURS` INT DEFAULT 0,
  `PROFESSION_CLEANER_COUNT` INT DEFAULT 0,
  `STATUS` VARCHAR(20) DEFAULT NULL,
  `CREATED_DT` timestamp NULL DEFAULT NULL,
  `UPDATED_DT` timestamp NULL DEFAULT current_timestamp(),
   PRIMARY KEY (`ID`),
   KEY `IDX_BOOKING_ID` (`BOOKING_ID`),
   KEY `IDX_CUSTOMER_ID` (`CUSTOMER_ID`),

   CONSTRAINT `FK_BOOKING_USERS`
     FOREIGN KEY (`CUSTOMER_ID`)
     REFERENCES `USERS`(`ID`)
     ON DELETE CASCADE
);

CREATE TABLE `BOOKING_CLEANERS` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `BOOKING_ID` BIGINT NOT NULL,
  `PROFESSIONAL_CLEANER_ID` BIGINT NOT NULL,
  `ASSIGNMENT_STATUS` VARCHAR(20) DEFAULT 'ASSIGNED',
  `CREATED_DT` timestamp NULL DEFAULT NULL,
  `UPDATED_DT` timestamp NULL DEFAULT current_timestamp(),
   PRIMARY KEY (`ID`),
   KEY `IDX_BOOKING_ID` (`BOOKING_ID`),
   KEY `IDX_PROFESSIONAL_CLEANER_ID` (`PROFESSIONAL_CLEANER_ID`),

   CONSTRAINT `FK_BOOKING_CLEANERS_APPOINTMENTS`
     FOREIGN KEY (`BOOKING_ID`)
     REFERENCES `BOOKINGS`(`ID`)
     ON DELETE CASCADE,

   CONSTRAINT `FK_BOOKING_CLEANERS_PROFESSIONAL`
     FOREIGN KEY (`PROFESSIONAL_CLEANER_ID`)
     REFERENCES `PROFESSIONAL`(`ID`)
     ON DELETE CASCADE
);

CREATE TABLE `SYSTEM_RULES` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `RULE_KEY` VARCHAR(50) NOT NULL UNIQUE,
  `RULE_VALUE` VARCHAR(50) NOT NULL,
  `UPDATED_DT` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
   PRIMARY KEY (`ID`)
);

